#!/usr/bin/env bash
# Replace the installed winjitsu package with a "nightly" built from this
# checkout, uncommitted changes included. For developers on Arch Linux.
#
# It builds a pacman package, so the package database stays consistent and the
# next AUR release upgrades it normally: the version is <tag>.r<commits>.g<hash>
# (plus .dirty with uncommitted changes), newer than that tag and older than the
# next one. Package metadata (depends, description...) comes from arch/PKGBUILD.
#
#   ./install-nightly.sh               build, install with pacman, reload the daemon
#   ./install-nightly.sh --no-install  only build, the package is left in PKGs/
#
# Back to the official package: reinstall winjitsu from the AUR (yay -S winjitsu).
set -euo pipefail

install=true
case "${1:-}" in
    "")           ;;
    --no-install) install=false ;;
    -h|--help)    awk 'NR > 1 && /^#/ { sub(/^# ?/, ""); print; next } NR > 1 { exit }' "$0"; exit 0 ;;
    *)            echo "Unknown option: $1 (see --help)" >&2; exit 2 ;;
esac

repo=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
cd "$repo"

for tool in git makepkg python; do
    command -v "$tool" >/dev/null || { echo "Missing $tool." >&2; exit 1; }
done
python -c "import build, installer, setuptools" 2>/dev/null \
    || { echo "Missing build tools: sudo pacman -S python-build python-installer python-setuptools python-wheel" >&2; exit 1; }

# --- Version ---------------------------------------------------------------
describe=$(git describe --tags --long --match 'v[0-9]*')   # v0.4.2-6-g25dd865
version=$(sed -E 's/^v//; s/-([0-9]+)-(g[0-9a-f]+)$/.r\1.\2/' <<<"$describe")
if [[ -n $(git status --porcelain --untracked-files=normal) ]]; then
    version+=".dirty"
    echo "Note: building uncommitted changes too (version $version)."
fi

workdir=$(mktemp -d -t winjitsu-nightly.XXXXXX)
trap 'rm -rf "$workdir"' EXIT

# --- Wheel ------------------------------------------------------------------
# Built from a copy of the files git would see (tracked and untracked, minus
# ignored ones), so the checkout isn't touched by build/ and *.egg-info.
mkdir "$workdir/tree"
git ls-files -z --cached --others --exclude-standard | while IFS= read -r -d '' file; do
    if [[ -e $file ]]; then   # skip tracked files deleted in the working tree
        cp --parents -- "$file" "$workdir/tree/"
    fi
done

echo "==> Building the wheel"
python -m build --wheel --no-isolation --outdir "$workdir/dist" "$workdir/tree" >"$workdir/build.log" 2>&1 \
    || { cat "$workdir/build.log" >&2; exit 1; }
wheel=$(basename "$workdir"/dist/*.whl)

# --- Package ----------------------------------------------------------------
mkdir "$workdir/pkgbuild"
cp "$workdir/dist/$wheel" "$workdir/pkgbuild/"
# The variables below come from arch/PKGBUILD.
# shellcheck disable=SC1091,SC2154
(
    source arch/PKGBUILD
    cat >"$workdir/pkgbuild/PKGBUILD" <<EOF
# Generated by install-nightly.sh from arch/PKGBUILD.
pkgname=$pkgname
pkgver=$version
pkgrel=1
pkgdesc=$(printf '%q' "$pkgdesc (nightly)")
arch=($(printf '%q ' "${arch[@]}"))
url=$(printf '%q' "$url")
license=($(printf '%q ' "${license[@]}"))
depends=($(printf '%q ' "${depends[@]}"))
makedepends=(python-installer)
source=($(printf '%q' "$wheel"))
sha256sums=(SKIP)

package() {
    python -m installer --destdir="\$pkgdir" "\$srcdir/$wheel"
}
EOF
)

echo "==> Building the package winjitsu $version-1"
makepkg_flags=(--force --clean)
if $install; then
    makepkg_flags+=(--syncdeps --install)
fi
(
    cd "$workdir/pkgbuild"
    PKGDEST="$workdir/out" SRCDEST="$workdir/pkgbuild" BUILDDIR="$workdir/makepkg" makepkg "${makepkg_flags[@]}"
)

if ! $install; then
    package=$(basename "$workdir"/out/*.pkg.tar.*)
    mkdir -p PKGs
    cp "$workdir/out/$package" PKGs/
    echo "==> Package left in: PKGs/$package"
    echo "    Install it with: sudo pacman -U PKGs/$package"
    exit 0
fi

echo "==> Installed: $(pacman -Q winjitsu)"

# --- Daemon -----------------------------------------------------------------
# A running daemon keeps the old code loaded until it is restarted.
pid_file="${XDG_RUNTIME_DIR:-/run/user/$(id -u)}/winjitsu/winjitsu.pid"
if [[ -f $pid_file ]] && kill -0 "$(cat "$pid_file")" 2>/dev/null; then
    echo "==> Reloading the daemon"
    /usr/bin/winjitsu --reload-daemon
else
    echo "==> No daemon running. Start it with: winjitsu --daemon"
fi
